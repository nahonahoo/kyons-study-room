// ⑨ 相似比 1:2 は4枚、1:3 は9枚
function tile(n, s, ox, oy, c){
  var h = 0.866 * s, out = '';
  for (var i = 0; i <= n; i++) {
    out += ln([ox + i * s / 2, oy - i * h], [ox + n * s - i * s / 2, oy - i * h], c, 2);
    out += ln([ox + i * s, oy], [ox + n * s / 2 + i * s / 2, oy - (n - i) * h], c, 2);
    out += ln([ox + n * s - i * s, oy], [ox + n * s / 2 - i * s / 2, oy - (n - i) * h], c, 2);
  }
  return out;
}
