document.addEventListener('click', function(e){
  var t = e.target.closest ? e.target.closest('button') : null;
  if(!t) return;
  if(t.getAttribute('data-range')){ settings.range = t.getAttribute('data-range'); saveSettings(); renderChips(); return; }
  if(t.getAttribute('data-count') !== null){ settings.count = parseInt(t.getAttribute('data-count'), 10); saveSettings(); renderChips(); return; }
  if(t.getAttribute('data-nch') !== null){ settings.nch = parseInt(t.getAttribute('data-nch'), 10); saveSettings(); renderChips(); return; }
  if(t.id === 'btnReveal'){ reveal(); return; }
  if(t.getAttribute('data-lv')){ settings.lv = t.getAttribute('data-lv'); saveSettings(); renderChips(); return; }
  if(t.getAttribute('data-time')){ settings.time = parseInt(t.getAttribute('data-time'), 10); saveSettings(); renderChips(); return; }
  if(t.classList.contains('ch') && t.getAttribute('data-k') !== null){ answer(parseInt(t.getAttribute('data-k'), 10)); return; }
});
document.addEventListener('keydown', function(e){
  if(!G || $('scrGame').classList.contains('hide')) return;
  if(!G.answered && G.self){
    if(!G.revealed && (e.key === ' ' || e.key === 'Enter')){ reveal(); e.preventDefault(); return; }
    if(G.revealed && e.key === '1'){ finish(true, G.qs[G.i].a, false); e.preventDefault(); return; }
    if(G.revealed && e.key === '2'){ finish(false, '（思い出せなかった）', false); e.preventDefault(); return; }
    return;
  }
  if(!G.answered && e.key >= '1' && e.key <= String(G.order.length)){ answer(parseInt(e.key, 10) - 1); e.preventDefault(); return; }
  if(G.answered && (e.key === 'Enter' || e.key === ' ')){ nextQuestion(); e.preventDefault(); }
});
