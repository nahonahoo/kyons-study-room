// 図はすべて問題の数字から座標を計算して描く。用語は math_c3_similar.js にそろえる。

var C_A = '#ff7eb6', C_B = '#4dd0ff', C_C = '#ffd84d', C_LINE = '#e6edf3', C_DIM = '#7d8797', C_G = '#58e08a', C_R = '#ff6b6b';
function f(n){ return Math.round(n * 10) / 10; }
function svg(w, h, label, body){ return '<svg viewBox="0 0 ' + w + ' ' + h + '" role="img" aria-label="' + label + '" style="width:100%;max-width:560px;display:block;margin:0 auto">' + body + '</svg>'; }
function ln(p, q, c, w, dash){ return '<line x1="' + f(p[0]) + '" y1="' + f(p[1]) + '" x2="' + f(q[0]) + '" y2="' + f(q[1]) + '" stroke="' + c + '" stroke-width="' + (w || 2.5) + '"' + (dash ? ' stroke-dasharray="6,5"' : '') + '/>'; }
function poly(pts, c, fill){ return '<polygon points="' + pts.map(function(p){ return f(p[0]) + ',' + f(p[1]); }).join(' ') + '" fill="' + (fill || 'none') + '" stroke="' + c + '" stroke-width="2.5"/>'; }
function dot(p, c, r){ return '<circle cx="' + f(p[0]) + '" cy="' + f(p[1]) + '" r="' + (r || 6) + '" fill="' + c + '"/>'; }
function tx(x, y, s, c, size, anchor){ return '<text x="' + f(x) + '" y="' + f(y) + '" fill="' + (c || C_LINE) + '" font-size="' + (size || 16) + '" font-weight="800" text-anchor="' + (anchor || 'middle') + '">' + s + '</text>'; }
function arc(P, Q, R, r, c){
  var a1 = Math.atan2(Q[1] - P[1], Q[0] - P[0]), a2 = Math.atan2(R[1] - P[1], R[0] - P[0]), d = a2 - a1;
  while (d <= -Math.PI) d += 2 * Math.PI;
  while (d > Math.PI) d -= 2 * Math.PI;
  return '<path d="M' + f(P[0] + r * Math.cos(a1)) + ' ' + f(P[1] + r * Math.sin(a1)) + ' A' + r + ' ' + r + ' 0 0 ' + (d > 0 ? 1 : 0) + ' ' + f(P[0] + r * Math.cos(a2)) + ' ' + f(P[1] + r * Math.sin(a2)) + '" fill="none" stroke="' + c + '" stroke-width="3.5"/>';
}
// 3辺（AB, BC, CA）から三角形を作る。B が (ox, oy)、C は右（flip なら左）、A は上。
function triPts(ab, bc, ca, s, ox, oy, flip){
  var x = (ab * ab - ca * ca + bc * bc) / (2 * bc), y = Math.sqrt(ab * ab - x * x), k = flip ? -1 : 1;
  return [[ox + k * x * s, oy - y * s], [ox, oy], [ox + k * bc * s, oy]];
}
function center(P){ return [(P[0][0] + P[1][0] + P[2][0]) / 3, (P[0][1] + P[1][1] + P[2][1]) / 3]; }
function away(p, g, d){ var dx = p[0] - g[0], dy = p[1] - g[1], L = Math.sqrt(dx * dx + dy * dy) || 1; return [p[0] + dx / L * d, p[1] + dy / L * d]; }
function mid(p, q){ return [(p[0] + q[0]) / 2, (p[1] + q[1]) / 2]; }
function along(p, q, t){ return [p[0] + (q[0] - p[0]) * t, p[1] + (q[1] - p[1]) * t]; }
var VC = [C_A, C_B, C_C];
// 頂点を色つきの点と文字で描く
function vertices(P, names, d){
  var g = center(P), h = '';
  P.forEach(function(p, i){ var q = away(p, g, d || 20); h += dot(p, VC[i]) + tx(q[0], q[1] + 6, names[i], VC[i], 16); });
  return h;
}
function sideNum(p, q, g, s, c){ var m = away(mid(p, q), g, 15); return tx(m[0], m[1] + 6, s, c || C_LINE, 16); }

// 陣形の名前は、下の2人を線の下に置く（点と重ならないように）
function stageNames(P, n){
  return dot(P[0], C_A) + tx(P[0][0], P[0][1] - 12, n[0], C_A) + dot(P[1], C_B) + tx(P[1][0], P[1][1] + 26, n[1], C_B) + dot(P[2], C_C) + tx(P[2][0], P[2][1] + 26, n[2], C_C);
}
// ① 小劇場と大劇場（4・6・5 の陣形を 2 倍）
function figStage(){
  var a = triPts(4, 6, 5, 13, 52, 150), b = triPts(4, 6, 5, 26, 205, 170), ga = center(a), gb = center(b);
  var n = ['吉野', 'つるまる', '竹内'];
  return svg(420, 240, '小さい三角形と、同じ形で2倍の三角形',
    poly(a, C_LINE, 'rgba(255,255,255,0.05)') + poly(b, C_LINE, 'rgba(255,255,255,0.05)')
    + sideNum(a[0], a[1], ga, '4') + sideNum(a[1], a[2], ga, '6') + sideNum(a[2], a[0], ga, '5')
    + sideNum(b[0], b[1], gb, '8', C_G) + sideNum(b[1], b[2], gb, '12', C_G) + sideNum(b[2], b[0], gb, '10', C_G)
    + stageNames(a, n) + stageNames(b, n)
    + tx(92, 230, '小劇場', C_DIM, 15) + tx(283, 230, '大劇場（間隔が全部2倍）', C_G, 15));
}
