function f(n){ return Math.round(n * 10) / 10; }
function svg(w, h, label, body){ return '<svg viewBox="0 0 ' + w + ' ' + h + '" role="img" aria-label="' + label + '" style="width:100%;max-width:560px;display:block;margin:0 auto">' + body + '</svg>'; }
function ln(x1, y1, x2, y2, c, w, dash){ return '<line x1="' + f(x1) + '" y1="' + f(y1) + '" x2="' + f(x2) + '" y2="' + f(y2) + '" stroke="' + c + '" stroke-width="' + (w || 2.5) + '"' + (dash ? ' stroke-dasharray="6,5"' : '') + '/>'; }
function tx(x, y, s, c, size, anchor){ return '<text x="' + f(x) + '" y="' + f(y) + '" fill="' + (c || C_LINE) + '" font-size="' + (size || 16) + '" font-weight="800" text-anchor="' + (anchor || 'middle') + '">' + s + '</text>'; }
function ar(x1, y1, x2, y2, c, w){
  var dx = x2 - x1, dy = y2 - y1, L = Math.sqrt(dx * dx + dy * dy), ux = dx / L, uy = dy / L, h = 13, s = 7;
  var bx = x2 - ux * h, by = y2 - uy * h;
  return ln(x1, y1, bx, by, c, w || 4) + '<polygon points="' + f(x2) + ',' + f(y2) + ' ' + f(bx - uy * s) + ',' + f(by + ux * s) + ' ' + f(bx + uy * s) + ',' + f(by - ux * s) + '" fill="' + c + '"/>';
}
function rect(x, y, w, h, c, fill){ return '<rect x="' + f(x) + '" y="' + f(y) + '" width="' + f(w) + '" height="' + f(h) + '" fill="' + (fill || 'none') + '" stroke="' + c + '" stroke-width="2.5"/>'; }
function table(rows){
  var h = '<div class="pair-wrap"><table class="pair-table">';
  rows.forEach(function(r, i){
    h += '<tr>' + r.map(function(c){ return (i === 0 ? '<th>' : '<td>') + c + (i === 0 ? '</th>' : '</td>'); }).join('') + '</tr>';
  });
  return h + '</table></div>';
}
