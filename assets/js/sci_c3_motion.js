// 矢印（先に三角）
function Ar(x1, y1, x2, y2, color, w) {
  var dx = x2 - x1, dy = y2 - y1, L = Math.sqrt(dx * dx + dy * dy), ux = dx / L, uy = dy / L, h = 9, s = 5;
  var bx = x2 - ux * h, by = y2 - uy * h;
  return Ln(x1, y1, bx, by, color, w || 2.5)
    + '<polygon points="' + r1(x2) + ',' + r1(y2) + ' ' + r1(bx - uy * s) + ',' + r1(by + ux * s) + ' ' + r1(bx + uy * s) + ',' + r1(by - ux * s) + '" fill="' + color + '"/>';
}
